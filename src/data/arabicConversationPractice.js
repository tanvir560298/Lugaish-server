function buildQuestions(coreQuestions, language, day, mode) {
  return coreQuestions.map(item => ({
    ...item,
    id: `${language}-conversation-${item.id}-day-${day}`,
    language,
    maxMarks: 10,
    scoringStrategy: mode === 'ask' ? 'question_reading' : item.scoringStrategy,
  }));
}

